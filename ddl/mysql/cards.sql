-- MySQL: Endnutzer-Datenbank, eine Zeile pro Kartendruck (Printing)
CREATE TABLE IF NOT EXISTS cards (
    id              VARCHAR(64)   NOT NULL,
    multiverse_id   INT           NULL,
    name            VARCHAR(255)  NOT NULL,
    mana_cost       VARCHAR(100)  NULL,
    cmc             DOUBLE        NULL,
    colors          VARCHAR(50)   NULL,
    color_identity  VARCHAR(50)   NULL,
    type            VARCHAR(255)  NULL,
    supertypes      VARCHAR(255)  NULL,
    types           VARCHAR(255)  NULL,
    subtypes        VARCHAR(255)  NULL,
    rarity          VARCHAR(50)   NULL,
    set_code        VARCHAR(20)   NULL,
    set_name        VARCHAR(255)  NULL,
    text            TEXT          NULL,
    flavor          TEXT          NULL,
    artist          VARCHAR(255)  NULL,
    number          VARCHAR(20)   NULL,
    power           VARCHAR(20)   NULL,
    toughness       VARCHAR(20)   NULL,
    loyalty         VARCHAR(20)   NULL,
    layout          VARCHAR(50)   NULL,
    image_url       VARCHAR(500)  NULL,
    has_image       TINYINT       NOT NULL DEFAULT 0,
    printings_count INT           NOT NULL DEFAULT 1,
    load_date       DATE          NOT NULL,
    color_names     VARCHAR(100)  NULL,
    name_de         VARCHAR(255)  NULL,
    search_name     VARCHAR(600)  NULL,
    search_all      TEXT          NULL,
    PRIMARY KEY (id),
    KEY idx_cards_name (name),
    KEY idx_cards_artist (artist),
    KEY idx_cards_multiverse_id (multiverse_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
